<?php
/**
 * XSL stylesheet that makes sitemaps readable in a browser.
 *
 * @package TagwrightSEO
 */

namespace TagwrightSEO\Sitemaps;

defined( 'ABSPATH' ) || exit;

/**
 * Renders the stylesheet. Search engines ignore it; humans get a tidy table.
 */
class Stylesheet {

	/**
	 * Returns the XSL document.
	 *
	 * @return string
	 */
	public static function render() {
		$title       = esc_html__( 'XML Sitemap', 'tagwright-seo' );
		$intro       = esc_html__( 'This sitemap is generated by Tagwright SEO. It helps search engines like Google and Bing find every page on this site.', 'tagwright-seo' );
		/* translators: %s: number of sitemaps. */
		$index_count = esc_html__( 'This index lists %s sitemaps.', 'tagwright-seo' );
		/* translators: %s: number of URLs. */
		$url_count   = esc_html__( 'This sitemap lists %s URLs.', 'tagwright-seo' );
		$back        = esc_html__( 'Back to the sitemap index', 'tagwright-seo' );
		$col_sitemap = esc_html__( 'Sitemap', 'tagwright-seo' );
		$col_url     = esc_html__( 'URL', 'tagwright-seo' );
		$col_images  = esc_html__( 'Images', 'tagwright-seo' );
		$col_freq    = esc_html__( 'Change frequency', 'tagwright-seo' );
		$col_prio    = esc_html__( 'Priority', 'tagwright-seo' );
		$col_lastmod = esc_html__( 'Last modified', 'tagwright-seo' );
		$index_url   = esc_url( Router::index_url() );
		$css_url     = esc_url( add_query_arg( 'ver', TAGWRIGHT_SEO_VERSION, TAGWRIGHT_SEO_URL . 'assets/css/sitemap.css' ) );

		list( $index_before, $index_after ) = array_pad( explode( '%s', $index_count, 2 ), 2, '' );
		list( $url_before, $url_after )     = array_pad( explode( '%s', $url_count, 2 ), 2, '' );

		// Placeholders are filled with the escaped values above.
		// A sitemap is an XML document styled through XSL, so there is no wp_head()
		// to enqueue on; the browser loads our own static stylesheet from the <link>.
		// phpcs:disable WordPress.WP.EnqueuedResources.NonEnqueuedStylesheet
		$template = '<?xml version="1.0" encoding="UTF-8"?>
<xsl:stylesheet version="2.0"
	xmlns:html="http://www.w3.org/TR/REC-html40"
	xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"
	xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9"
	xmlns:xsl="http://www.w3.org/1999/XSL/Transform">
<xsl:output method="html" version="1.0" encoding="UTF-8" indent="yes"/>
<xsl:template match="/">
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
	<title>{{title}}</title>
	<meta name="viewport" content="width=device-width, initial-scale=1" />
	<link rel="stylesheet" type="text/css" href="{{css_url}}" />
</head>
<body>
	<header>
		<h1>{{title}}</h1>
		<p>{{intro}}</p>
	</header>
	<main>
		<div class="card">
			<xsl:choose>
				<xsl:when test="count(sitemap:sitemapindex/sitemap:sitemap) &gt; 0">
					<div class="meta">
						<span>{{index_before}}<span class="pill"><xsl:value-of select="count(sitemap:sitemapindex/sitemap:sitemap)"/></span>{{index_after}}</span>
					</div>
					<table>
						<tr><th>{{col_sitemap}}</th><th class="date">{{col_lastmod}}</th></tr>
						<xsl:for-each select="sitemap:sitemapindex/sitemap:sitemap">
							<tr>
								<td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td>
								<td class="date"><xsl:value-of select="concat(substring(sitemap:lastmod,0,11),\' \',substring(sitemap:lastmod,12,5))"/></td>
							</tr>
						</xsl:for-each>
					</table>
				</xsl:when>
				<xsl:otherwise>
					<div class="meta">
						<span>{{url_before}}<span class="pill"><xsl:value-of select="count(sitemap:urlset/sitemap:url)"/></span>{{url_after}}</span>
						<a href="{{index_url}}">&#8592; {{back}}</a>
					</div>
					<table>
						<tr><th>{{col_url}}</th><th class="num">{{col_prio}}</th><th class="num">{{col_freq}}</th><th class="num">{{col_images}}</th><th class="date">{{col_lastmod}}</th></tr>
						<xsl:for-each select="sitemap:urlset/sitemap:url">
							<tr>
								<td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td>
								<td class="num"><xsl:value-of select="sitemap:priority"/></td>
								<td class="num"><xsl:value-of select="sitemap:changefreq"/></td>
								<td class="num"><xsl:value-of select="count(image:image)"/></td>
								<td class="date"><xsl:value-of select="concat(substring(sitemap:lastmod,0,11),\' \',substring(sitemap:lastmod,12,5))"/></td>
							</tr>
						</xsl:for-each>
					</table>
				</xsl:otherwise>
			</xsl:choose>
		</div>
	</main>
</body>
</html>
</xsl:template>
</xsl:stylesheet>';
		// phpcs:enable WordPress.WP.EnqueuedResources.NonEnqueuedStylesheet

		return strtr(
			$template,
			array(
				'{{title}}'        => $title,
				'{{intro}}'        => $intro,
				'{{index_before}}' => $index_before,
				'{{index_after}}'  => $index_after,
				'{{col_sitemap}}'  => $col_sitemap,
				'{{col_lastmod}}'  => $col_lastmod,
				'{{url_before}}'   => $url_before,
				'{{url_after}}'    => $url_after,
				'{{index_url}}'    => $index_url,
				'{{css_url}}'      => $css_url,
				'{{back}}'         => $back,
				'{{col_url}}'      => $col_url,
				'{{col_prio}}'     => $col_prio,
				'{{col_freq}}'     => $col_freq,
				'{{col_images}}'   => $col_images,
			)
		);
	}
}
